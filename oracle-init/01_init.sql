-- 0. COMPANIES 테이블 (회사/테넌트 정보)
CREATE TABLE COMPANIES (
    COMPANY_CODE VARCHAR2(50) PRIMARY KEY,
    COMPANY_NAME VARCHAR2(100) NOT NULL,
    BUSINESS_NO VARCHAR2(50),
    PLAN VARCHAR2(20) DEFAULT 'standard' CHECK (PLAN IN ('starter', 'standard', 'enterprise')),
    STATUS VARCHAR2(20) DEFAULT 'active' CHECK (STATUS IN ('active', 'suspended', 'inactive')),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 1. USERS 테이블 (사용자 정보)
CREATE TABLE USERS (
    UID_VAL VARCHAR2(128) PRIMARY KEY,
    EMAIL VARCHAR2(255) NOT NULL UNIQUE,
    NAME VARCHAR2(100) NOT NULL,
    ROLE VARCHAR2(20) DEFAULT 'employee' CHECK (ROLE IN ('employee', 'manager', 'admin')),
    COMPANY_CODE VARCHAR2(50) NOT NULL,
    TEAM_CODE VARCHAR2(50),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_USERS_COMPANY FOREIGN KEY (COMPANY_CODE) REFERENCES COMPANIES(COMPANY_CODE) ON DELETE CASCADE
);

-- 2. TRIPS 테이블 (출장 계획 정보)
CREATE TABLE TRIPS (
    ID VARCHAR2(128) PRIMARY KEY,
    USER_ID VARCHAR2(128) NOT NULL,
    TITLE VARCHAR2(255) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'upcoming' CHECK (STATUS IN ('upcoming', 'ongoing', 'completed', 'cancelled')),
    START_DATE VARCHAR2(10) NOT NULL,
    END_DATE VARCHAR2(10) NOT NULL,
    DESTINATION VARCHAR2(255) NOT NULL,
    ITINERARY_JSON CLOB,
    PURPOSE VARCHAR2(500),
    REPORT CLOB,
    COMPANY_CODE VARCHAR2(50) NOT NULL,
    TEAM_CODE VARCHAR2(50),
    IS_SHARED_WITH_TEAM NUMBER(1) DEFAULT 0 CHECK (IS_SHARED_WITH_TEAM IN (0, 1)),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_TRIPS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(UID_VAL) ON DELETE CASCADE,
    CONSTRAINT FK_TRIPS_COMPANY FOREIGN KEY (COMPANY_CODE) REFERENCES COMPANIES(COMPANY_CODE) ON DELETE CASCADE
);

-- 3. CHECK_INS 테이블 (GPS / NFC 체크인/체크아웃 기록)
CREATE TABLE CHECK_INS (
    ID VARCHAR2(128) PRIMARY KEY,
    USER_ID VARCHAR2(128) NOT NULL,
    TRIP_ID VARCHAR2(128) NOT NULL,
    TS_MILLIS NUMBER(15) NOT NULL,
    LOCATION_NAME VARCHAR2(255) NOT NULL,
    LAT NUMBER(10,7),
    LNG NUMBER(10,7),
    TYPE_VAL VARCHAR2(20) NOT NULL CHECK (TYPE_VAL IN ('check-in', 'check-out')),
    VERIFIED NUMBER(1) DEFAULT 1 CHECK (VERIFIED IN (0, 1)),
    ITINERARY_ITEM_ID VARCHAR2(128),
    COMPANY_CODE VARCHAR2(50) NOT NULL,
    NFC_TAG_ID VARCHAR2(128),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_CHECKINS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(UID_VAL) ON DELETE CASCADE,
    CONSTRAINT FK_CHECKINS_TRIP FOREIGN KEY (TRIP_ID) REFERENCES TRIPS(ID) ON DELETE CASCADE,
    CONSTRAINT FK_CHECKINS_COMPANY FOREIGN KEY (COMPANY_CODE) REFERENCES COMPANIES(COMPANY_CODE) ON DELETE CASCADE
);

-- 4. EXPENSES 테이블 (경비 정산 영수증 기록)
CREATE TABLE EXPENSES (
    ID VARCHAR2(128) PRIMARY KEY,
    USER_ID VARCHAR2(128) NOT NULL,
    TRIP_ID VARCHAR2(128) NOT NULL,
    EXPENSE_DATE VARCHAR2(10) NOT NULL,
    MERCHANT VARCHAR2(255) NOT NULL,
    AMOUNT NUMBER(12,2) NOT NULL,
    CATEGORY VARCHAR2(50) NOT NULL,
    IMAGE_URL VARCHAR2(1000),
    COMPANY_CODE VARCHAR2(50) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_EXPENSES_USER FOREIGN KEY (USER_ID) REFERENCES USERS(UID_VAL) ON DELETE CASCADE,
    CONSTRAINT FK_EXPENSES_TRIP FOREIGN KEY (TRIP_ID) REFERENCES TRIPS(ID) ON DELETE CASCADE,
    CONSTRAINT FK_EXPENSES_COMPANY FOREIGN KEY (COMPANY_CODE) REFERENCES COMPANIES(COMPANY_CODE) ON DELETE CASCADE
);

-- 기본 인덱스 생성
CREATE INDEX IDX_TRIPS_USER ON TRIPS(USER_ID);
CREATE INDEX IDX_CHECKINS_TRIP ON CHECK_INS(TRIP_ID);
CREATE INDEX IDX_EXPENSES_TRIP ON EXPENSES(TRIP_ID);
CREATE INDEX IDX_CHECKINS_USER ON CHECK_INS(USER_ID);
CREATE INDEX IDX_EXPENSES_USER ON EXPENSES(USER_ID);

-- 테넌트(회사코드) 최적화 복합 인덱스 생성
CREATE INDEX IDX_USERS_COMP_ROLE ON USERS(COMPANY_CODE, ROLE);
CREATE INDEX IDX_TRIPS_COMP_USER ON TRIPS(COMPANY_CODE, USER_ID);
CREATE INDEX IDX_TRIPS_COMP_STATUS ON TRIPS(COMPANY_CODE, STATUS);
CREATE INDEX IDX_CHECKINS_COMP_TRIP ON CHECK_INS(COMPANY_CODE, TRIP_ID);
CREATE INDEX IDX_EXPENSES_COMP_TRIP ON EXPENSES(COMPANY_CODE, TRIP_ID);

COMMIT;
